"""Write RegMix experiment scale manifest and phi scale-transfer coefficients."""

from __future__ import annotations

import numpy as np
import pandas as pd

from pathlib import Path


OUT = Path(__file__).resolve().parent / "results"


def main() -> None:
    manifest = pd.DataFrame([
        {
            "dataset_id": "A4/A5", "role": "train", "scale_label": "1M",
            "file_mixture": "train_mixture_1m.csv", "file_loss": "train_pile_loss_1m.csv",
            "n_mixtures": 512, "N_params": int(1e6), "N_unit": "non-embedding parameters",
            "D_tokens": int(1e9), "D_unit": "tokens", "loss_type": "observed",
            "repeats_per_mixture": 1, "repeat_status": "single run per mixture in provided table",
            "evidence": "RegMix paper Table 2/Appendix: 512 x 1M models trained on 1B tokens",
        },
        {
            "dataset_id": "A6/A7", "role": "test", "scale_label": "1M",
            "file_mixture": "test_mixture_1m.csv", "file_loss": "test_pile_loss_1m.csv",
            "n_mixtures": 256, "N_params": int(1e6), "N_unit": "non-embedding parameters",
            "D_tokens": int(1e9), "D_unit": "tokens", "loss_type": "observed",
            "repeats_per_mixture": 1, "repeat_status": "single run per mixture; no seed/repeat column",
            "evidence": "RegMix paper Table 2: 256 unseen mixtures for 1M models on 1B tokens",
        },
        {
            "dataset_id": "A8/A9", "role": "test", "scale_label": "60M",
            "file_mixture": "test_mixture_60m.csv", "file_loss": "test_pile_loss_60m.csv",
            "n_mixtures": 256, "N_params": int(6e7), "N_unit": "non-embedding parameters",
            "D_tokens": int(1e9), "D_unit": "tokens", "loss_type": "observed",
            "repeats_per_mixture": 1, "repeat_status": "single run per mixture; no seed/repeat column",
            "evidence": "RegMix paper Table 2/Appendix: 60M models trained on 1B tokens",
        },
        {
            "dataset_id": "A10/A11", "role": "test", "scale_label": "1B",
            "file_mixture": "test_mixture_1B.csv", "file_loss": "test_pile_loss_1B.csv",
            "n_mixtures": 64, "N_params": int(1e9), "N_unit": "non-embedding parameters",
            "D_tokens": int(25e9), "D_unit": "tokens", "loss_type": "observed",
            "repeats_per_mixture": 1, "repeat_status": "single run per mixture; no seed/repeat column",
            "evidence": "RegMix paper Table 2/Appendix: 64 x 1B models trained on 25B tokens",
        },
        {
            "dataset_id": "A12/A13", "role": "extrapolation", "scale_label": "10B",
            "file_mixture": "est_mixture_10b.csv", "file_loss": "est_pile_loss_10b.csv",
            "n_mixtures": 63, "N_params": int(1e10), "N_unit": "parameters (label)",
            "D_tokens": "not specified", "D_unit": "not specified in provided data", "loss_type": "extrapolated",
            "repeats_per_mixture": "not applicable", "repeat_status": "not applicable: loss is estimated, not a new run",
            "evidence": "Competition data description labels A12/A13 as extrapolation",
        },
        {
            "dataset_id": "A14/A15", "role": "extrapolation", "scale_label": "70B",
            "file_mixture": "est_mixture_70b.csv", "file_loss": "est_pile_loss_70b.csv",
            "n_mixtures": 63, "N_params": int(7e10), "N_unit": "parameters (label)",
            "D_tokens": "not specified", "D_unit": "not specified in provided data", "loss_type": "extrapolated",
            "repeats_per_mixture": "not applicable", "repeat_status": "not applicable: loss is estimated, not a new run",
            "evidence": "Competition data description labels A14/A15 as extrapolation",
        },
    ])
    manifest.to_csv(OUT / "regmix_experiment_manifest.csv", index=False, encoding="utf-8-sig")

    # Scale transfer for the mixture-ranking signal generated by the 1M model.
    B = pd.read_csv(OUT / "B_multitask_sparse_scheffe.csv", index_col=0).to_numpy(dtype=float)
    rows = []
    for key, label, n_params, d_tokens in (
        ("test_1m", "1M", 1e6, 1e9),
        ("test_60m", "60M", 6e7, 1e9),
        ("test_1b", "1B", 1e9, 25e9),
        ("est_10b", "10B", 1e10, np.nan),
        ("est_70b", "70B", 7e10, np.nan),
    ):
        pred = pd.read_csv(OUT / f"X2_{key}.csv").to_numpy(dtype=float) @ B
        obs = pd.read_csv(OUT / f"Z_{key}.csv").to_numpy(dtype=float)
        g_pred = pred.mean(axis=1)
        g_obs = obs.mean(axis=1)
        slope, intercept = np.polyfit(g_pred, g_obs, 1)
        r2 = 1 - np.sum((g_obs - (intercept + slope * g_pred)) ** 2) / np.sum((g_obs - g_obs.mean()) ** 2)
        rows.append({
            "scale_label": label, "n_mixtures": len(g_pred), "N_params": n_params,
            "D_tokens": d_tokens if np.isfinite(d_tokens) else "not specified",
            "slope_b": float(slope), "intercept_a": float(intercept), "r2_linear": float(r2),
            "loss_type": "observed" if np.isfinite(d_tokens) else "extrapolated",
            "use_in_q2": "yes" if np.isfinite(d_tokens) else "boundary_only",
            "note": "G_scale(p) = a + b * G_1M(p); use slope sign/CI only for observed scales."
                    if np.isfinite(d_tokens) else "Extrapolated scale; do not calibrate Q2 absolute scaling.",
        })
    transfer = pd.DataFrame(rows)
    transfer.to_csv(OUT / "phi_scale_transfer.csv", index=False, encoding="utf-8-sig")
    print(manifest.to_string(index=False))
    print(transfer.to_string(index=False))


if __name__ == "__main__":
    main()
